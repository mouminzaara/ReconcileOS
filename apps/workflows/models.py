"""
Models for ReconcileOS Remediation & Repair Planning Engine.
"""

import uuid
from django.db import models
from django.conf import settings
from django.utils.translation import gettext_lazy as _
from apps.rules.models import RuleSeverity


class PlanStatus(models.TextChoices):
    """
    Status lifecycle of a repair plan.
    """
    PENDING = 'PENDING', _('Pending')
    APPROVED = 'APPROVED', _('Approved')
    REJECTED = 'REJECTED', _('Rejected')
    EXECUTING = 'EXECUTING', _('Executing')
    RETRYING = 'RETRYING', _('Retrying')
    SUCCESS = 'SUCCESS', _('Success')
    COMPLETED = 'COMPLETED', _('Completed')
    FAILED = 'FAILED', _('Failed')


class RepairPlan(models.Model):
    """
    Represents a safe, deterministic repair plan generated by ReconcileOS
    to address an identified integrity violation (authorization drift).
    """
    id = models.UUIDField(
        primary_key=True,
        default=uuid.uuid4,
        editable=False,
        help_text=_("Unique identifier for the repair plan (UUIDv4).")
    )
    employee = models.ForeignKey(
        'employees.Employee',
        on_delete=models.CASCADE,
        related_name='repair_plans',
        help_text=_("Employee associated with this repair plan.")
    )
    violation = models.ForeignKey(
        'reconciliation.IntegrityViolation',
        on_delete=models.CASCADE,
        related_name='repair_plans',
        help_text=_("Target integrity violation that this plan intends to repair.")
    )
    target_system = models.CharField(
        max_length=50,
        db_index=True,
        help_text=_("Downstream target system where repair action will apply (e.g. VPN).")
    )
    action = models.CharField(
        max_length=100,
        help_text=_("Deterministic repair action title (e.g. DISABLE VPN ACCESS).")
    )
    reason = models.TextField(
        help_text=_("Detailed rationale for the intended repair plan.")
    )
    risk_level = models.CharField(
        max_length=20,
        choices=RuleSeverity.choices,
        default=RuleSeverity.HIGH,
        db_index=True,
        help_text=_("Risk / Sensitivity level of the repair action.")
    )
    status = models.CharField(
        max_length=20,
        choices=PlanStatus.choices,
        default=PlanStatus.PENDING,
        db_index=True,
        help_text=_("Current lifecycle status of the repair plan.")
    )

    created_at = models.DateTimeField(
        auto_now_add=True,
        help_text=_("Timestamp when the repair plan was created.")
    )
    updated_at = models.DateTimeField(
        auto_now=True,
        help_text=_("Timestamp when the repair plan record was last updated.")
    )

    class Meta:
        ordering = ['-created_at']
        verbose_name = _('Repair Plan')
        verbose_name_plural = _('Repair Plans')
        indexes = [
            models.Index(fields=['status', 'risk_level']),
            models.Index(fields=['employee', 'status']),
            models.Index(fields=['violation', 'status']),
        ]

    def __str__(self):
        return (
            f"Repair Plan [{self.status}]: {self.action} for {self.employee.full_name} "
            f"[{self.target_system}] (Violation ID: {self.violation_id})"
        )

    @property
    def sensitivity_level(self):
        """
        Alias for risk_level to satisfy sensitivity level access patterns.
        """
        return self.risk_level


class ExecutionStatus(models.TextChoices):
    """
    Status of an individual repair plan execution attempt.
    """
    PENDING = 'PENDING', _('Pending')
    EXECUTING = 'EXECUTING', _('Executing')
    RETRYING = 'RETRYING', _('Retrying')
    SUCCESS = 'SUCCESS', _('Success')
    FAILED = 'FAILED', _('Failed')


class RepairExecutionLog(models.Model):
    """
    Records execution attempt details, output logs, and results for a RepairPlan.
    Tracks operation_id, attempt_number, status, error, and timestamps.
    """
    id = models.UUIDField(
        primary_key=True,
        default=uuid.uuid4,
        editable=False,
        help_text=_("Unique identifier for the execution record (UUIDv4) / operation_id.")
    )
    repair_plan = models.ForeignKey(
        RepairPlan,
        on_delete=models.CASCADE,
        related_name='execution_logs',
        help_text=_("Associated repair plan.")
    )
    executed_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='repair_executions_triggered',
        help_text=_("User who triggered the repair plan execution.")
    )
    attempt_number = models.IntegerField(
        default=1,
        help_text=_("Attempt counter for this execution run.")
    )
    idempotency_key = models.CharField(
        max_length=255,
        blank=True,
        default='',
        db_index=True,
        help_text=_("Deterministic idempotency key for this execution attempt.")
    )
    already_satisfied = models.BooleanField(
        default=False,
        help_text=_("Whether pre-execution check recognized that desired target state was already satisfied.")
    )
    status = models.CharField(
        max_length=20,
        choices=ExecutionStatus.choices,
        default=ExecutionStatus.PENDING,
        db_index=True,
        help_text=_("Status of the execution run.")
    )
    output_message = models.TextField(
        blank=True,
        default='',
        help_text=_("Output message or summary returned by connector execution.")
    )
    error_details = models.TextField(
        blank=True,
        default='',
        help_text=_("Error traceback or failure explanation if execution failed.")
    )
    started_at = models.DateTimeField(
        auto_now_add=True,
        help_text=_("Timestamp when execution started.")
    )
    completed_at = models.DateTimeField(
        null=True,
        blank=True,
        help_text=_("Timestamp when execution finished.")
    )

    class Meta:
        ordering = ['started_at']
        verbose_name = _('Repair Execution Log')
        verbose_name_plural = _('Repair Execution Logs')

    def __str__(self):
        return f"Execution Attempt #{self.attempt_number} [{self.status}]: Plan ID {self.repair_plan_id} at {self.started_at}"

    @property
    def operation_id(self) -> str:
        """Alias for UUID primary key to satisfy operation_id access patterns."""
        return str(self.id)

    @property
    def error(self) -> str:
        """Alias for error_details."""
        return self.error_details


class VerificationResult(models.TextChoices):
    """
    Result outcome of post-repair verification check.
    """
    PENDING = 'PENDING', _('Pending')
    VERIFIED = 'VERIFIED', _('Verified')
    VERIFICATION_FAILED = 'VERIFICATION_FAILED', _('Verification Failed')


class RepairVerification(models.Model):
    """
    Records post-repair empirical verification outcome re-querying downstream target system state.
    """
    id = models.UUIDField(
        primary_key=True,
        default=uuid.uuid4,
        editable=False,
        help_text=_("Unique identifier for the verification record (UUIDv4).")
    )
    repair_plan = models.ForeignKey(
        RepairPlan,
        on_delete=models.CASCADE,
        related_name='verifications',
        help_text=_("Target repair plan undergoing verification.")
    )
    expected_state = models.CharField(
        max_length=50,
        help_text=_("Expected value required by invariant rule (e.g. DISABLED).")
    )
    actual_state = models.CharField(
        max_length=50,
        help_text=_("Empirically observed actual state in target system after repair.")
    )
    result = models.CharField(
        max_length=30,
        choices=VerificationResult.choices,
        default=VerificationResult.PENDING,
        db_index=True,
        help_text=_("Outcome of verification check (VERIFIED or VERIFICATION_FAILED).")
    )
    verified_at = models.DateTimeField(
        null=True,
        blank=True,
        help_text=_("Timestamp when verification check was completed.")
    )
    details = models.TextField(
        blank=True,
        default='',
        help_text=_("Detailed rationale, logs, or diagnostic output for the verification check.")
    )

    created_at = models.DateTimeField(
        auto_now_add=True,
        help_text=_("Timestamp when verification record was created.")
    )
    updated_at = models.DateTimeField(
        auto_now=True,
        help_text=_("Timestamp when verification record was last updated.")
    )

    class Meta:
        ordering = ['-created_at']
        verbose_name = _('Repair Verification')
        verbose_name_plural = _('Repair Verifications')

    def __str__(self):
        return f"Verification [{self.result}]: Plan ID {self.repair_plan_id} (Actual: {self.actual_state}, Expected: {self.expected_state})"
